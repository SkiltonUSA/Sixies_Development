void art_load_screen(uint8_t index) BANKED {
    if (index == 0u) {
        LCDC_REG &= (uint8_t)~LCDCF_BG8000;
        set_bkg_data(0u, 255u, title_screen_tiles);
        set_sprite_data(0u, ART_TITLE_PROMPT_TILES, title_prompt_tiles);
        set_bkg_tiles(0u, 0u, 20u, 18u, title_screen_map);
        if (_cpu == CGB_TYPE) {
            set_bkg_palette(0u, 1u, (const palette_color_t *)title_screen_palettes);
            VBK_REG = 1u;
            set_bkg_tiles(0u, 0u, 20u, 18u, title_screen_attributes);
            VBK_REG = 0u;
        }
    }
    if (index == 1u) {
        
        set_bkg_data(0u, 255u, game_over_screen_tiles);
        
        set_bkg_tiles(0u, 0u, 20u, 18u, game_over_screen_map);
        if (_cpu == CGB_TYPE) {
            set_bkg_palette(0u, 1u, (const palette_color_t *)game_over_screen_palettes);
            VBK_REG = 1u;
            set_bkg_tiles(0u, 0u, 20u, 18u, game_over_screen_attributes);
            VBK_REG = 0u;
        }
    }
    if (index == 2u) {
        
        set_bkg_data(0u, 209u, intro_screen_tiles);
        set_sprite_data(ART_INTRO_VERSION_BASE, ART_INTRO_VERSION_TILES, intro_version_tiles);
        set_bkg_tiles(0u, 0u, 20u, 18u, intro_screen_map);
        if (_cpu == CGB_TYPE) {
            set_bkg_palette(0u, 1u, (const palette_color_t *)intro_screen_palettes);
            VBK_REG = 1u;
            set_bkg_tiles(0u, 0u, 20u, 18u, intro_screen_attributes);
            VBK_REG = 0u;
        }
    }
}
