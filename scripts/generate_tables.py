print()

emit_word_table("crawl_screen_rows", [C64_SCREEN + row * SCREEN_WIDTH for row in crawl_rows])
emit_word_table("crawl_color_rows", [C64_COLOR + row * SCREEN_WIDTH for row in crawl_rows])
emit_byte_table("crawl_widths", row_widths)
emit_byte_table("crawl_starts", [(SCREEN_WIDTH - width) // 2 for width in row_widths])
emit_byte_table("crawl_offsets", row_offsets)
emit_byte_table("crawl_colors", row_colors)
print()

emit_word_table("reflect_screen_rows", [C64_SCREEN + row * SCREEN_WIDTH for row in reflect_rows])
emit_word_table("reflect_color_rows", [C64_COLOR + row * SCREEN_WIDTH for row in reflect_rows])
emit_byte_table("reflect_widths", reflect_widths)
emit_byte_table("reflect_starts", [(SCREEN_WIDTH - width) // 2 for width in reflect_widths])
emit_byte_table("reflect_offsets", reflect_offsets)
emit_byte_table("reflect_colors", reflect_colors)
print()

emit_byte_table("star_pos_lo", [(C64_SCREEN + pos) & 0xff for pos in stars])
emit_byte_table("star_pos_hi", [((C64_SCREEN + pos) >> 8) & 0xff for pos in stars])
emit_byte_table("star_color_lo", [(C64_COLOR + pos) & 0xff for pos in stars])
emit_byte_table("star_color_hi", [((C64_COLOR + pos) >> 8) & 0xff for pos in stars])
print()

for idx, (_, title) in enumerate(title_lines):
    emit_byte_table(f"title_{idx}", centered(title))
print("title_screen_lo:")
print("    !byte " + ",".join(f"<${C64_SCREEN + row * SCREEN_WIDTH:04x}" for row, _ in title_lines))
print("title_screen_hi:")
print("    !byte " + ",".join(f">${C64_SCREEN + row * SCREEN_WIDTH:04x}" for row, _ in title_lines))
print("title_color_lo:")
print("    !byte " + ",".join(f"<${C64_COLOR + row * SCREEN_WIDTH:04x}" for row, _ in title_lines))
print("title_color_hi:")
print("    !byte " + ",".join(f">${C64_COLOR + row * SCREEN_WIDTH:04x}" for row, _ in title_lines))
print("title_line_lo:")
print("    !byte " + ",".join(f"<title_{idx}" for idx in range(len(title_lines))))
print("title_line_hi:")
print("    !byte " + ",".join(f">title_{idx}" for idx in range(len(title_lines))))
