#!/usr/bin/env python3

from __future__ import annotations

SCREEN_WIDTH = 40
C64_SCREEN = 0x0400
C64_COLOR = 0xD800


def screen_code(ch: str) -> int:
    ch = ch.upper()
    if "A" <= ch <= "Z":
        return ord(ch) - ord("A") + 1
    if "0" <= ch <= "9":
        return ord(ch)
    if ch in " .,!?:-/+*":
        return ord(ch)
    return 32


def centered(text: str) -> list[int]:
    text = text.upper()[:SCREEN_WIDTH]
    left = (SCREEN_WIDTH - len(text)) // 2
    line = (" " * left + text).ljust(SCREEN_WIDTH)
    return [screen_code(ch) for ch in line]


